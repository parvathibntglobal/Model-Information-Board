"""The board curation proposals, turned into the contract and into rulings.

    python docs/proposals/board_curation.py write-contract --dsn <url> <proposal>...
    python docs/proposals/board_curation.py apply <proposal> --dsn <url> [--undo] [--coordinated]

A PROPOSAL MODULE (`*_curation_2026_10_14.py`) carries:
    SECTION    best_for | capability | metric
    PARENTS    heading key -> heading name, at most ten
    CLUSTERS   kept slug -> (heading key, [slugs merged into it])
    DECLINE    slug -> reason
    UNFILED    slug -> reason (optional): kept, under no heading on purpose
    NAMES      slug -> name (optional): a name a person chose, which wins

write-contract  rewrites `parent_names` and `sections` in
                contract/slug_parents.yaml, and the whole of
                contract/board_vocabulary.yaml, from the proposals given. A
                merged slug is filed under its target's heading, so a row not
                yet ruled still groups beside the name it is meant to join.
                A slug's name, in this order (`choose_name`): the proposal's
                NAMES; else the name already in the vocabulary file; else, for
                a NEW slug only, the commonest name among its rows in the
                database; else one made from the slug. Every pinned name and
                every new slug is printed, for a person to read (#606).

apply           rules each merged slug `merged` into its target and each
                declined slug `declined`, through `rule_entries` - the same call
                the Admin review makes, so each ruling can also be undone there.
                `--undo` reverses them all. Nothing is deleted. Running it IS
                the ruling (rule 10): run it only for a proposal a person has
                read. LOCAL BY DEFAULT - any host but localhost needs
                `--coordinated`, because shared-database writes are announced
                and taken by one person at a time. Each run writes a record
                beside the proposal.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import sys
from datetime import UTC, datetime
from pathlib import Path
from urllib.parse import urlparse

import psycopg
import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

PARENTS_FILE = ROOT / "contract" / "slug_parents.yaml"
VOCABULARY_FILE = ROOT / "contract" / "board_vocabulary.yaml"
SECTION_ORDER = ("best_for", "capability", "metric")
LOCAL_HOSTS = {"localhost", "127.0.0.1", "::1"}

VOCABULARY_HEADER = """\
# THE VOCABULARY THE EXTRACTOR IS SHOWN, per board section. First generated
# 2026-10-14, last regenerated {regenerated}, by
# `docs/proposals/board_curation.py write-contract` from the curation
# proposals beside it: every slug a proposal KEEPS and files under a heading,
# with its name. Names merged into one of these are not listed - offering them
# would invite the duplicates the merge removes. Edit a proposal and
# regenerate; do not edit this file by hand.
#
# A NAME HERE IS KEPT ON REGENERATION (#606). Only a name a proposal sets in
# `NAMES` replaces it. The database's commonest name for a slug is used for a
# NEW slug alone: taken for every slug, it would have renamed 41 on 2026-11-06,
# some plausibly and wrongly (`humaneval` -> "Coding benchmarks"), and each
# rename is a change to the extractor's prompt.
#
# WHAT THIS IS AND IS NOT. A REUSE-FIRST list, not a closed one. The extractor
# is told to reuse a listed slug whenever one names what the quote reports,
# and when none does, to name a new one and file it under one of the headings
# (`parent`). Code never refuses a new slug: a membership check here would be
# the closed vocabulary `judge/config.py:board_exemplars` warns against, which
# forces a quote into the nearest wrong name.
#
# NO COUNTS (rule 11). How many reports each holds is the board's to compute.
"""


def load(path: str):
    spec = importlib.util.spec_from_file_location(Path(path).stem, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def filed(p) -> dict[str, list[str]]:
    """{heading: [every slug filed under it]} - each kept slug, then the slugs
    proposed to merge into it."""
    out: dict[str, list[str]] = {h: [] for h in p.PARENTS}
    for target, (heading, merged) in p.CLUSTERS.items():
        out[heading] += [target, *merged]
    return {h: slugs for h, slugs in out.items() if slugs}


def existing_names(path: Path = VOCABULARY_FILE) -> dict[tuple[str, str], str]:
    """{(section, slug): name} as the vocabulary file holds them now."""
    if not path.exists():
        return {}
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return {
        (section, item["slug"]): item["name"]
        for section, heads in raw.items()
        for items in (heads or {}).values()
        for item in items
    }


def choose_name(
    section: str,
    slug: str,
    *,
    pinned: dict[str, str],
    existing: dict[tuple[str, str], str],
    from_db: dict[tuple[str, str], str],
) -> tuple[str, str]:
    """(name, where it came from) for one kept slug.

    A pin is a person's choice. An existing name was in the file and stays: the
    database's commonest name is a fallback that answers plausibly when it is
    wrong (rule 12), so it names a slug the file does not have yet, and only
    that. A slug with no rows is named from itself, as before.
    """
    if slug in pinned:
        return pinned[slug], "pinned"
    if (section, slug) in existing:
        return existing[(section, slug)], "kept"
    if from_db.get((section, slug)):
        return from_db[(section, slug)], "new, from the database"
    return slug.replace("-", " ").capitalize(), "new, from the slug"


def write_contract(dsn: str, proposals: list) -> None:
    by_section = {p.SECTION: p for p in proposals}
    missing = [s for s in SECTION_ORDER if s not in by_section]
    if missing:
        raise SystemExit(f"write-contract needs a proposal for every section; missing {missing}")
    # A pin for a slug the proposal does not keep would be dropped without a
    # word, and the name somebody chose would never reach the file (rule 12).
    stray = [
        f"{p.SECTION}/{slug}" for p in proposals
        for slug in getattr(p, "NAMES", {}) if slug not in p.CLUSTERS
    ]
    if stray:
        raise SystemExit(f"NAMES pins a slug its proposal does not keep: {stray}")

    # ── slug_parents.yaml: parent_names and sections, nothing else ──────────
    text = PARENTS_FILE.read_text(encoding="utf-8")
    head, _, rest = text.partition("\nparent_names:\n")
    _, _, _old_sections = rest.partition("\nsections:\n")
    names = ["parent_names:"]
    for section in SECTION_ORDER:
        names.append(f"  # {section}")
        names += [f"  {k}: {v}" for k, v in by_section[section].PARENTS.items()]
    body = ["sections:"]
    for section in SECTION_ORDER:
        body.append(f"  {section}:")
        for heading, slugs in filed(by_section[section]).items():
            body.append(f"    {heading}:")
            body += [f"      - {s}" for s in slugs]
    PARENTS_FILE.write_text(
        head + "\n" + "\n".join(names) + "\n\n" + "\n".join(body) + "\n", encoding="utf-8"
    )

    # ── board_vocabulary.yaml ────────────────────────────────────────────────
    with psycopg.connect(dsn) as conn:
        rows = conn.execute(
            "SELECT section, slug, mode() WITHIN GROUP (ORDER BY name) "
            "FROM board_entry GROUP BY section, slug"
        ).fetchall()
    names_of = {(s, g): n for s, g, n in rows}
    existing = existing_names()
    vocab: dict[str, dict[str, list[dict[str, str]]]] = {}
    unnamed = []
    to_read = []
    for section in SECTION_ORDER:
        p = by_section[section]
        pinned = getattr(p, "NAMES", {})
        vocab[section] = {h: [] for h in p.PARENTS}
        for target, (heading, _merged) in p.CLUSTERS.items():
            name, source = choose_name(
                section, target, pinned=pinned, existing=existing, from_db=names_of
            )
            # The header's note means "no rows on the database this was
            # generated from", whichever way the name was then chosen.
            if source != "pinned" and not names_of.get((section, target)):
                unnamed.append(f"{section}/{target}")
            before = existing.get((section, target))
            if source.startswith("new") or (source == "pinned" and name != before):
                to_read.append(f"  {section}/{target}: {before!r} -> {name!r} ({source})")
            vocab[section][heading].append({"slug": target, "name": name})
        vocab[section] = {h: items for h, items in vocab[section].items() if items}
    # The date is written by the run that writes the file, so it cannot go stale
    # the way a typed one did (rule 11).
    out = VOCABULARY_HEADER.replace("{regenerated}", datetime.now(UTC).date().isoformat())
    if unnamed:
        out += (
            "# Named from the slug - no rows on the database this was generated from:\n#   "
            + ", ".join(unnamed)
            + "\n"
        )
    VOCABULARY_FILE.write_text(
        out + "\n" + yaml.safe_dump(vocab, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    for section in SECTION_ORDER:
        p = by_section[section]
        print(
            f"{section}: {len(p.PARENTS)} headings, {len(p.CLUSTERS)} kept and filed, "
            f"{sum(len(m) for _h, m in p.CLUSTERS.values())} merged, {len(p.DECLINE)} declined, "
            f"{len(getattr(p, 'UNFILED', {}))} unfiled"
        )
    # Every name a person has to read before this reaches the extractor's prompt.
    print(f"names to read ({len(to_read)}): pinned changes and new slugs")
    print("\n".join(to_read) if to_read else "  none")


def apply(dsn: str, path: str, *, undo: bool, coordinated: bool) -> int:
    from judge.store.board_entries import rule_entries, unrule_entries

    host = urlparse(dsn).hostname or ""
    if host not in LOCAL_HOSTS and not coordinated:
        print(
            f"refused: {host!r} is not a local database. Writes to the shared one are "
            "coordinated - announce it, then pass --coordinated."
        )
        return 2
    p = load(path)
    plan = [(s, "merged", t) for t, (_h, merged) in p.CLUSTERS.items() for s in merged]
    plan += [(s, "declined", None) for s in p.DECLINE]
    record = {
        "proposal": path,
        "section": p.SECTION,
        "undo": undo,
        "at": datetime.now(UTC).isoformat(),
        "database_host": host,
        "ruled": {},
        "no_rows": [],
    }
    with psycopg.connect(dsn) as conn:
        for slug, ruling, target in plan:
            n = (
                unrule_entries(conn, section=p.SECTION, slug=slug)
                if undo
                else rule_entries(
                    conn, section=p.SECTION, slug=slug, ruling=ruling, ruling_target=target
                )
            )
            if n:
                record["ruled"][slug] = {"ruling": ruling, "target": target, "rows": n}
            else:
                record["no_rows"].append(slug)
        conn.commit()
    out = Path(path).with_suffix(f".{'undo' if undo else 'applied'}.json")
    out.write_text(json.dumps(record, indent=1), encoding="utf-8")
    print(
        f"{'undid' if undo else 'ruled'} {len(record['ruled'])} {p.SECTION} slugs "
        f"({sum(v['rows'] for v in record['ruled'].values())} rows); "
        f"{len(record['no_rows'])} had no rows here. Record: {out}"
    )
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write-contract")
    w.add_argument("--dsn", required=True)
    w.add_argument("proposals", nargs="+")
    a = sub.add_parser("apply")
    a.add_argument("proposal")
    a.add_argument("--dsn", required=True)
    a.add_argument("--undo", action="store_true")
    a.add_argument("--coordinated", action="store_true")
    args = ap.parse_args()
    if args.cmd == "write-contract":
        write_contract(args.dsn, [load(x) for x in args.proposals])
        return 0
    return apply(args.dsn, args.proposal, undo=args.undo, coordinated=args.coordinated)


if __name__ == "__main__":
    sys.exit(main())
